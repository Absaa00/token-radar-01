// The token radar's model (radar-2): one sealed snapshot in, one ranked board out.
//
// The board covers every slug in the snapshot's watchlist (the floor, never a ceiling) and adds
// every pre-token protocol below the watchlist floor that the house's own rule would keep: not a
// wrapped, staked or bridged product of a token that already trades, not a versioned pool, not an
// exchange. Protocols above the floor that the watchlist leaves out stay out: the house left them
// out on DefiLlama's parent-protocol record, which the snapshot does not carry, so this model does
// not second-guess it. Live-token protocols are kept apart and shown with the market's own values.
//
// Implied value is calibrated from the snapshot itself, not from a flat guess: for each category,
// the base multiple is the MEDIAN market-cap / TVL of the live-token protocols in that category
// (three or more comparables, clamped to [0.08, 0.90]); a category with fewer live comparables
// uses the global median across all live protocols. Then:
//
//   implied = tvl_usd x category_multiple
//           x (1 + clamp(change_7d, -40, 60) / 100 x 0.5)      growth
//           x (0.7 + min(age_days, 1095) / 1095 x 0.3)          maturity
//           x (1 + 0.02 x min(chains - 1, 10))                  breadth
//
// Growth rewards momentum, maturity rewards time run with no token (an unlisted age uses 365
// days), breadth rewards reach across chains. No protocol name is ever special-cased: the same
// function scores every row, and the dashboard shows each row's four factors.

/** The snapshot's protocol entry: exactly the ten fields the sealed input carries. */
export interface SnapshotProtocol {
  slug: string;
  name: string;
  category: string | null;
  chains: string[];
  tvl_usd: number;
  change_7d: number | null;
  mcap_usd: number | null;
  listed_at: string | null;
  gecko_id: string | null;
  symbol: string | null;
}

/** The whole snapshot document. */
export interface Snapshot {
  as_of: string;
  source: string;
  floor_usd: number;
  protocols: SnapshotProtocol[];
  watchlist: string[];
}

/** The model's constants, as the dashboard states them and the sandbox may change them. */
export interface ModelConstants {
  growth_weight: number;
  growth_floor: number;
  growth_cap: number;
  maturity_floor: number;
  maturity_range: number;
  maturity_days: number;
  unknown_age_days: number;
  multiple_floor: number;
  multiple_cap: number;
  min_comparables: number;
  breadth_per_chain: number;
  breadth_max_chains: number;
}

export const MODEL: ModelConstants = {
  growth_weight: 0.5,
  growth_floor: -40,
  growth_cap: 60,
  maturity_floor: 0.7,
  maturity_range: 0.3,
  maturity_days: 1095,
  unknown_age_days: 365,
  multiple_floor: 0.08,
  multiple_cap: 0.9,
  min_comparables: 3,
  breadth_per_chain: 0.02,
  breadth_max_chains: 10,
};

/** The model's version label: the dashboard names it and the rules quote it. */
export const MODEL_VERSION = 'radar-2';

